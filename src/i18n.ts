export function translateText(value: string, language: AppLanguage) {
  if (language === "en") {
    return value;
  }

  const exactTranslation = frenchTranslations[value];
  if (exactTranslation) {
    return exactTranslation;
  }

  const mealCount = value.match(/^(\d+) meals?$/i);
  if (mealCount) {
    return `${mealCount[1]} repas`;
  }

  const storageSummary = value.match(/^(\d+) meals? · (.+)$/i);
  if (storageSummary) {
    return `${storageSummary[1]} repas · ${storageSummary[2]}`;
  }

  const uppercaseMealCount = value.match(/^(\d+) MEALS?$/);
  if (uppercaseMealCount) {
    return `${uppercaseMealCount[1]} REPAS`;
  }

  const removeAction = value.match(/^Delete (.+)$/);
  if (removeAction) {
    return `Supprimer ${removeAction[1]}`;
  }

  const editAction = value.match(/^Edit (.+)$/);
  if (editAction) {
    return `Modifier ${editAction[1]}`;
  }

  const keepAction = value.match(/^Keep “(.+)”$/);
  if (keepAction) {
    return `Garder « ${keepAction[1]} »`;
  }

  const noMeals = value.match(/^No meals logged for (.+) yet\.$/);
  if (noMeals) {
    const category =
      frenchTranslations[noMeals[1]] ??
      frenchTranslations[
        `${noMeals[1][0]?.toUpperCase()}${noMeals[1].slice(1)}`
      ] ??
      noMeals[1];
    return `Aucun repas enregistré pour ${category.toLowerCase()} pour le moment.`;
  }

  const welcome = value.match(/^Welcome, (.+)\.$/);
  if (welcome) {
    return `Bienvenue, ${welcome[1]}.`;
  }

  const removedMeal = value.match(/^(.+) removed from your diary$/);
  if (removedMeal) {
    return `${removedMeal[1]} supprimé du journal`;
  }

  const gramLabel = value.match(/^(.+) in grams$/);
  if (gramLabel) {
    const ingredient = frenchTranslations[gramLabel[1]] ?? gramLabel[1];
    return `${ingredient} en grammes`;
  }

  const overGoal = value.match(/^Over goal by (.+) kcal$/);
  if (overGoal) {
    return `Objectif dépassé de ${overGoal[1]} kcal`;
  }

  const remaining = value.match(/^(.+) kcal remaining(?: after adding)?\.?$/);
  if (remaining) {
    return `${remaining[1]} kcal restantes${value.includes("after adding") ? " après ajout" : ""}`;
  }

  const goalRange = value.match(
    /^Choose a goal between 1 and ([\d,]+) kcal\.$/,
  );
  if (goalRange) {
    return `Choisissez un objectif entre 1 et ${goalRange[1]} kcal.`;
  }

  const removalConfirmation = value.match(
    /^(.+) will be removed from your diary\.$/,
  );
  if (removalConfirmation) {
    return `${removalConfirmation[1]} sera supprimé de votre journal.`;
  }

  const translatedAccessibility = value
    .replace(", meals recorded", ", repas enregistrés")
    .replace(/, today$/, ", aujourd’hui");
  if (translatedAccessibility !== value) {
    return translatedAccessibility;
  }

  return value;
}
